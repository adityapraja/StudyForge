export default function Sidebar({ mode, onNavChange, user, onLogout, isMobileOpen, setIsMobileOpen }) {
  const { isDark } = useTheme();

  const handleItemClick = (item) => {
    onNavChange(item);
    if (setIsMobileOpen) setIsMobileOpen(false);
  };

  return (
    <>
      {/* Mobile Backdrop overlay */}
      {isMobileOpen ? (
        <div
          className="sidebar-backdrop"
          onClick={() => setIsMobileOpen(false)}
          aria-hidden="true"
        />
      ) : null}

      <aside className={`app-sidebar ${isMobileOpen ? 'open' : ''}`}>
        {/* Brand header */}
        <div className="sidebar-brand">
          <img
            src={isDark ? '/studyforge-dark.svg' : '/studyforge.svg'}
            alt="StudyForge Logo"
            className="brand-logo"
            width="28"
            height="28"
          />
          <div className="brand-text">
            <strong>StudyForge</strong>
          </div>
          {setIsMobileOpen ? (
            <button
              type="button"
              className="sidebar-close-btn"
              onClick={() => setIsMobileOpen(false)}
              aria-label="Close navigation"
            >
              ✕
            </button>
          ) : null}
        </div>

        {/* Navigation list */}
        <nav className="sidebar-nav" aria-label="Main navigation">
          {NAV_ITEMS.map(([item, label]) => {
            const isActive = mode === item;
            return (
              <button
                key={item}
                type="button"
                aria-current={isActive ? 'page' : undefined}
                className={`sidebar-nav-item ${isActive ? 'active' : ''}`}
                onClick={() => handleItemClick(item)}
              >
                <span className="sidebar-nav-icon">{NAV_ICONS[item]}</span>
                <span className="sidebar-nav-label">{label}</span>
              </button>
            );
          })}
        </nav>

        {/* User profile footer */}
        <div className="sidebar-footer">
          <div className="sidebar-user-card">
            <div className="sidebar-user-avatar">
              {(user?.username || 'U').charAt(0).toUpperCase()}
            </div>
            <div className="sidebar-user-meta">
              <strong className="sidebar-username">{user?.username || 'Student'}</strong>
              <small className="sidebar-user-level">Lv. {user?.level || 1} · {user?.xp || 0} XP</small>
            </div>
          </div>
          <ThemeToggle variant="sidebar" />
          <button
            type="button"
            className="ghost-button sidebar-logout-btn"
            onClick={onLogout}
          >
            Log out
          </button>
        </div>
      </aside>
    </>
  );
}

